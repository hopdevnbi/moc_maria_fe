export type EditorKey = (typeof rows)[number][0];
const index: Record<Locale, 1 | 2 | 3 | 4 | 5 | 6> = {
  vi: 1,
  en: 2,
  ko: 3,
  ja: 4,
  "zh-CN": 5,
  ru: 6,
};
export const editorMessageKeys = rows.map((r) => r[0]);
export function editorMessage(locale: Locale, key: EditorKey) {
  const row = rows.find((r) => r[0] === key);
  return row?.[index[locale]] ?? row?.[1];
}
